MAX_SLIDES = 20
MAX_LINES = 80


class DocumentGenerationError(Exception):
    pass


def _lines_from_request(payload: dict[str, Any], kind: str) -> list[str]:
    topic = str(payload.get("topic") or payload.get("title") or "").strip()
    if not topic:
        raise DocumentGenerationError("A topic or title is required.")
    audience = str(payload.get("audience") or "general readers").strip()
    style = str(payload.get("style") or "clear and direct").strip()
    language = str(payload.get("language") or "English").strip()
    supplied = payload.get("bullets") or payload.get("outline") or []
    bullets: list[str] = []
    if isinstance(supplied, list):
        bullets = [str(item).strip() for item in supplied if str(item).strip()]
    elif isinstance(supplied, str) and supplied.strip():
        bullets = [line.strip("- ").strip() for line in supplied.splitlines() if line.strip()]
    if not bullets:
        bullets = [
            f"Purpose: {topic}",
            f"Audience: {audience}",
            f"Style: {style}",
            f"Language: {language}",
            "This document was built from the parameters and outline you supplied.",
        ]
    header = f"{topic}"
    return [header, *[item[:240] for item in bullets[:MAX_LINES]]]


def _create_native_docx(lines: list[str]) -> bytes:
    if HAS_DOCX:
        doc = Document()
        # Title
        doc.add_heading(lines[0], level=0)
        # Meta info
        doc.add_paragraph(f"Generated by ChronicleAI Document Engine · {datetime.date.today().isoformat()}")
        doc.add_heading("Summary & Key Takeaways", level=1)
        for bullet in lines[1:]:
            doc.add_paragraph(bullet, style="List Bullet")
        
        buffer = io.BytesIO()
        doc.save(buffer)
        return buffer.getvalue()
    else:
        return _fallback_docx_bytes(lines)


def _fallback_docx_bytes(lines: list[str]) -> bytes:
    paragraphs = []
    for index, line in enumerate(lines):
        size = "32" if index == 0 else "24"
        paragraphs.append(
            "<w:p><w:pPr><w:spacing w:after=\"160\"/></w:pPr>"
            f"<w:r><w:rPr><w:sz w:val=\"{size}\"/></w:rPr><w:t xml:space=\"preserve\">{html.escape(line)}</w:t></w:r></w:p>"
        )
    document = (
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
        "<w:document xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\">"
        f"<w:body>{''.join(paragraphs)}"
        "<w:sectPr><w:pgSz w:w=\"12240\" w:h=\"15840\"/>"
        "<w:pgMar w:top=\"1440\" w:right=\"1440\" w:bottom=\"1440\" w:left=\"1440\"/></w:sectPr>"
        "</w:body></w:document>"
    )
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", (
            "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
            "<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">"
            "<Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>"
            "<Default Extension=\"xml\" ContentType=\"application/xml\"/>"
            "<Override PartName=\"/word/document.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml\"/>"
            "</Types>"
        ).encode("utf-8"))
        archive.writestr("_rels/.rels", (
            "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
            "<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">"
            "<Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"word/document.xml\"/>"
            "</Relationships>"
        ).encode("utf-8"))
        archive.writestr("word/document.xml", document.encode("utf-8"))
    return buffer.getvalue()


def _pptx_bytes(lines: list[str], slide_count: int) -> bytes:
    count = max(1, min(int(slide_count or 1), MAX_SLIDES, len(lines)))
    parts: dict[str, str] = {}
    slide_ids = []
    overrides = []
    rels = []

    for index in range(count):
        slide_part = f"ppt/slides/slide{index + 1}.xml"
        slide_ids.append(f"<p:sldId id=\"{256 + index}\" r:id=\"rId{index + 1}\"/>")
        rels.append(f"<Relationship Id=\"rId{index + 1}\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide\" Target=\"slides/slide{index + 1}.xml\"/>")
        overrides.append(f"<Override PartName=\"/{slide_part}\" ContentType=\"application/vnd.openxmlformats-officedocument.presentationml.slide+xml\"/>")
        slide_text = lines[index]
        parts[slide_part] = (
            "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
            "<p:sld xmlns:a=\"http://schemas.openxmlformats.org/drawingml/2006/main\" "
            "xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\" "
            "xmlns:p=\"http://schemas.openxmlformats.org/presentationml/2006/main\">"
            "<p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id=\"1\" name=\"\"/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>"
            "<p:grpSpPr><a:xfrm><a:off x=\"0\" y=\"0\"/><a:ext cx=\"0\" cy=\"0\"/><a:chOff x=\"0\" y=\"0\"/><a:chExt cx=\"0\" cy=\"0\"/></a:xfrm></p:grpSpPr>"
            "<p:sp><p:nvSpPr><p:cNvPr id=\"2\" name=\"Title\"/><p:cNvSpPr><a:spLocks noGrp=\"1\"/></p:cNvSpPr><p:nvPr><p:ph type=\"ctrTitle\"/></p:nvPr></p:nvSpPr>"
            "<p:spPr><a:xfrm><a:off x=\"685800\" y=\"2133600\"/><a:ext cx=\"7772400\" cy=\"1470025\"/></a:xfrm></p:spPr>"
            f"<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang=\"en-US\" sz=\"3600\" b=\"1\"/><a:t>{html.escape(slide_text)}</a:t></a:r></a:p></p:txBody></p:sp>"
            "</p:spTree></p:cSld><p:clrMapOvr><a:masterClrMap/></p:clrMapOvr></p:sld>"
        )

    parts["[Content_Types].xml"] = (
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
        "<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">"
        "<Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>"
        "<Default Extension=\"xml\" ContentType=\"application/xml\"/>"
        "<Override PartName=\"/ppt/presentation.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml\"/>"
        + "".join(overrides)
        + "</Types>"
    )
    parts["_rels/.rels"] = (
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
        "<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">"
        "<Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"ppt/presentation.xml\"/>"
        "</Relationships>"
    )
    parts["ppt/presentation.xml"] = (
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
        "<p:presentation xmlns:a=\"http://schemas.openxmlformats.org/drawingml/2006/main\" "
        "xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\" "
        "xmlns:p=\"http://schemas.openxmlformats.org/presentationml/2006/main\">"
        f"<p:sldIdLst>{''.join(slide_ids)}</p:sldIdLst>"
        "<p:sldSz cx=\"9144000\" cy=\"6858000\" type=\"screen4x3\"/>"
        "<p:notesSz cx=\"6858000\" cy=\"9144000\"/>"
        "</p:presentation>"
    )
    parts["ppt/_rels/presentation.xml.rels"] = (
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
        f"<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">{''.join(rels)}</Relationships>"
    )

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in parts.items():
            archive.writestr(name, content.encode("utf-8"))
    return buffer.getvalue()


def _pdf_bytes(lines: list[str]) -> bytes:
    # Generates a valid standard PDF 1.4 document
    title = lines[0] if lines else "Document"
    content_lines = lines[1:] if len(lines) > 1 else ["(No content provided)"]
    
    stream_content = f"BT /F1 18 Tf 50 750 Td ({title[:60]}) Tj ET\n"
    stream_content += f"BT /F2 10 Tf 50 730 Td (Generated by ChronicleAI Engine · {datetime.date.today().isoformat()}) Tj ET\n"
    
    y = 700
    for line in content_lines:
        safe_line = line.replace("(", r"\(").replace(")", r"\)")[:90]
        stream_content += f"BT /F2 11 Tf 60 {y} Td (* {safe_line}) Tj ET\n"
        y -= 22
        if y < 60:
            break

    stream_bytes = stream_content.encode("latin-1", errors="replace")
    length = len(stream_bytes)

    objects = [
        b"%PDF-1.4\n",
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n",
        f"4 0 obj\n<< /Length {length} >>\nstream\n".encode("ascii") + stream_bytes + b"\nendstream\nendobj\n",
        b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n",
        b"6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
    ]

    body = b"".join(objects)
    xref_offset = len(body)
    
    offsets = [0]
    curr = 0
    for obj in objects:
        offsets.append(curr)
        curr += len(obj)

    xref = f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n"
    for o in offsets[1:]:
        xref += f"{o:010d} 00000 n \n"
    
    trailer = f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n"
    return body + xref.encode("ascii") + trailer.encode("ascii")


def analyze_rows(rows: list[Any]) -> dict[str, Any]:
    if not rows:
        return {"row_count": 0, "rows_count": 0, "columns": [], "totals": {}}
    if isinstance(rows[0], (list, tuple)) and len(rows) > 1:
        df = pd.DataFrame(rows[1:], columns=rows[0])
    else:
        df = pd.DataFrame(rows)
    totals: dict[str, float] = {}
    for col in df.columns:
        if pd.api.types.is_numeric_dtype(df[col]):
            totals[str(col)] = float(df[col].sum())
    return {
        "row_count": len(df),
        "rows_count": len(df),
        "columns": list(df.columns),
        "totals": totals,
        "sample": df.head(5).to_dict(orient="records"),
    }


def generate_document(kind: str, payload: dict[str, Any]) -> dict[str, Any]:
    kind = kind.lower().strip()
    if kind not in {"docx", "pptx", "pdf", "xlsx", "csv"}:
        raise DocumentGenerationError(f"Unsupported document kind: '{kind}'. Choose docx, pptx, pdf, xlsx, or csv.")

    lines = _lines_from_request(payload, kind)
    artifact_id = f"art_{uuid.uuid4().hex[:12]}"
    filename = f"{artifact_id}.{kind}"
    target_path = ARTIFACT_ROOT / filename

    if kind == "docx":
        raw_bytes = _create_native_docx(lines)
    elif kind == "pptx":
        slide_count = int(payload.get("slide_count") or len(lines))
        raw_bytes = _pptx_bytes(lines, slide_count)
    elif kind == "pdf":
        raw_bytes = _pdf_bytes(lines)
    elif kind in {"xlsx", "csv"}:
        rows = payload.get("rows")
        if isinstance(rows, list) and rows and isinstance(rows[0], (list, tuple)) and len(rows) > 1:
            df = pd.DataFrame(rows[1:], columns=rows[0])
        elif isinstance(rows, list):
            df = pd.DataFrame(rows)
        else:
            df = pd.DataFrame([{"topic": lines[0], "notes": bullet} for bullet in lines[1:]])
        buffer = io.BytesIO()
        if kind == "csv":
            df.to_csv(buffer, index=False)
        else:
            try:
                df.to_excel(buffer, index=False)
            except Exception:
                filename = f"{artifact_id}.csv"
                target_path = ARTIFACT_ROOT / filename
                kind = "csv"
                df.to_csv(buffer, index=False)
        raw_bytes = buffer.getvalue()
    else:
        raise DocumentGenerationError("Unsupported format")

    target_path.write_bytes(raw_bytes)
    if not target_path.exists() or target_path.stat().st_size == 0:
        raise DocumentGenerationError(f"File generation failed: {filename} was not created.")

    # Record artifact in database
    conn = get_db()
    try:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS artifacts (
                id TEXT PRIMARY KEY,
                kind TEXT NOT NULL,
                filename TEXT NOT NULL,
                path TEXT NOT NULL,
                byte_size INTEGER NOT NULL,
                created_at TEXT NOT NULL
            )
        """)
        conn.execute("""
            INSERT INTO artifacts (id, kind, filename, path, byte_size, created_at)
            VALUES (?, ?, ?, ?, ?, datetime('now'))
        """, (artifact_id, kind, filename, str(target_path), len(raw_bytes)))
        conn.commit()
    finally:
        conn.close()

    return {
        "id": artifact_id,
        "artifact_id": artifact_id,
        "kind": kind,
        "filename": filename,
        "bytes": len(raw_bytes),
        "download_path": f"/api/artifacts/{artifact_id}/download",
        "verified": True,
    }


def get_artifact(artifact_id: str) -> dict[str, Any] | None:
    conn = get_db()
    try:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM artifacts WHERE id = ?", (artifact_id,))
        row = cursor.fetchone()
        if not row:
            for f in ARTIFACT_ROOT.glob(f"{artifact_id}.*"):
                return {
                    "id": artifact_id,
                    "kind": f.suffix.lstrip("."),
                    "filename": f.name,
                    "path": str(f),
                }
            return None
        raw_path = row["path"] if "path" in row.keys() else row["file_path"]
        file_path = Path(raw_path)
        if not file_path.exists():
            return None
        byte_size = row["byte_size"] if "byte_size" in row.keys() else row.get("size_bytes", 0)
        return {
            "id": row["id"],
            "kind": row["kind"],
            "filename": row["filename"],
            "path": str(file_path),
            "size_bytes": byte_size,
        }
    except Exception:
        return None
    finally:
        conn.close()
